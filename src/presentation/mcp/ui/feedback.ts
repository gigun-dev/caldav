// =============================================================================
// 【このモジュールの位置づけ】todos-app/entry・agenda-app/entry の両方から使う「一過性
// アニメーションの寿命」を判定する純関数 + 定数のみを共有する。CSS/DOM そのものの共有化は
// §7.7 の判断どおり今回も見送り(S-A〜S-E で両ファイルが同時に揺れる最中に共有すると差分が
// レビュー不能になる)。rowKey(row-key.ts)と同じ規律 = 「新規に書く純関数・定数だけ共有」。
//
// 【ドクトリン v2 の要旨(詳細は §7.8 全文)】
//   全 mutate 操作を統一状態機械に載せる: tap → committing(寿命 1 周のアニメ)→ 満了で
//   即座に静的表現へ収束。楽観パス(結果を予測できる操作)は「保存中…」を挟まない
//   (楽観 = もう確定した体で見せる表現なので、待ち表示を挟むのは自己矛盾)。悲観パス
//   (結果を予測できない操作=反復イベントの start/end/recurrence 変更)だけ満了後に
//   静的「保存中…」タグへ移行し確定描画を待つ。
//
// 【なぜ「寿命チェック」を純関数として切り出すか】
//   委譲先(todos-app.ts の render 系・todos-entry.ts の pending 管理)が両方とも
//   「いま committing 中か」を判定する必要があり、判定式そのものは pendingIds の構造や
//   DOM に一切依存しない純粋な時刻比較。ロジックの単一情報源をここに置くことで、
//   cycleMs/animCycles を将来動かすときに1箇所の変更で両カードに効く(rowKey と同じ理由)。
// =============================================================================

/**
 * フィードバック視覚語彙の定数群。
 *
 * - cycleMs: アニメ1周期(ms)。skel pulse / wake-sweep と同一の 1.2s に固定
 *   (既存の視覚語彙をここでも流用するのが自然で、値を変えると「同じサイトなのに速度が違う」
 *   違和感を生む — 2026-07-16 ユーザー FB 由来の統一要求そのもの)。
 * - animCycles: committing の寿命 = cycleMs × animCycles。現在は 1 周(2026-07-16 ユーザー
 *   裁可: Fable 提案の「2周案」を「1周で十分・待たせすぎ」として取り下げ確定)。
 *   実測レイテンシ(p50=287ms/p90=1233ms/p95=1958ms、§7.8 根拠節)から、1周(1200ms)は
 *   p90 付近をちょうど覆う長さで、以降は無表示のまま裏で確定を待っても違和感がない。
 *   **将来レイテンシが変わったらこの整数だけ動かす**(他は触らない・可逆)。
 * - hardTimeoutMs: T_hard = 10s。Nielsen「注意持続の限界」(Response Times: The 3 Important
 *   Limits、原文確認済み・§7.8 根拠節)。これを超えたら警告バナー+再読み込み導線を出す
 *   (中断・ロールバックはしない — 遅着した成功が来たときに正しく確定描画へ収束させるため)。
 */
export const FEEDBACK = {
	cycleMs: 1200,
	animCycles: 1,
	hardTimeoutMs: 10_000,
} as const;

/**
 * 「いま committing(寿命付きアニメの最中)か」を時刻だけで判定する純関数。
 *
 * 【引数を (now, startedAt) の2値にした理由】呼び出し側(render 直前)が Date.now() を都度
 * 渡す形にし、この関数自体はタイマーも状態も持たない — テスト容易性(境界値をそのまま
 * now に渡して assert できる)と、setInterval 的な副作用をここに埋め込まない設計判断。
 *
 * 【境界は半開区間 [startedAt, startedAt+cycleMs*animCycles)】
 * 経過が寿命ちょうど(=1200ms)に達した時点でもう committing ではない(false)。
 * 「満了したら即座に静的表現へ収束」(§7.8)という設計そのものを等号の向きで表現している。
 */
export const isCommitting = (now: number, startedAt: number): boolean =>
	now - startedAt < FEEDBACK.cycleMs * FEEDBACK.animCycles;
